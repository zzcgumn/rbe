// Not a test binary: a plain program, invoked as a subprocess by the
// Python-side fixture ladder test, that prints every rung from fixtures.hpp
// to stdout as Python literals. Same "build both sides of every comparison
// from one description" mechanism as
// tests/belief_evaluation/parity_reference.cpp -- see that file's
// own header comment for why reading this program's own output is
// preferred over hand-transcribing the ladder a second time in Python.
#include <cstdint>
#include <cstdio>
#include <optional>

#include <api/dds_data_types.hpp>

#include <belief_evaluation/exhaustive_layout_source.hpp>

#include "fixtures.hpp"

namespace be = dds::belief_evaluation;
namespace bench = dds::belief_evaluation::benchmarks;

namespace
{
    auto print_deal(Deal const& deal) -> void
    {
        std::printf("        \"trump\": %d, \"first\": %d,\n", deal.trump, deal.first);
        std::printf("        \"remain_cards\": [\n");
        for (int hand = 0; hand < DDS_HANDS; ++hand)
        {
            std::printf(
                "            [%u, %u, %u, %u],\n", deal.remainCards[hand][0], deal.remainCards[hand][1],
                deal.remainCards[hand][2], deal.remainCards[hand][3]);
        }
        std::printf("        ],\n");
        std::printf(
            "        \"current_trick_suit\": (%d, %d, %d),\n", deal.currentTrickSuit[0],
            deal.currentTrickSuit[1], deal.currentTrickSuit[2]);
        std::printf(
            "        \"current_trick_rank\": (%d, %d, %d),\n", deal.currentTrickRank[0],
            deal.currentTrickRank[1], deal.currentTrickRank[2]);
    }

    auto print_rung(char const* python_name, bench::Rung const& rung) -> void
    {
        // Both forms share one root, one declarer, one tricks_needed --
        // Rung's own doxygen -- so the printed record carries the root
        // once, the history that distinguishes the two forms, and both
        // expected sizes, matching exactly what the with/without-history
        // pairing is meant to prove: the history parameter alone.
        std::uint64_t const unconstrained =
            *be::ExhaustiveLayoutSource(
                 rung.without_history.root, rung.without_history.declarer, /*seed=*/1u)
                 .size();
        std::uint64_t const constrained =
            *be::ExhaustiveLayoutSource(
                 rung.with_history.root, rung.with_history.declarer, /*seed=*/1u, rung.with_history.history,
                 rung.with_history.opening_leader)
                 .size();

        std::printf("%s = {\n", python_name);
        print_deal(rung.without_history.root);
        std::printf("        \"declarer\": %d,\n", rung.without_history.declarer);
        std::printf("        \"tricks_needed\": %d,\n", rung.without_history.tricks_needed);
        std::printf("        \"opening_leader\": %d,\n", rung.with_history.opening_leader);
        std::printf("        \"history\": [\n");
        PlayTraceBin const& history = rung.with_history.history;
        for (int i = 0; i < history.number; ++i)
        {
            std::printf("            (%d, %d),\n", history.suit[i], history.rank[i]);
        }
        std::printf("        ],\n");
        std::printf("        \"unconstrained_size\": %llu,\n", static_cast<unsigned long long>(unconstrained));
        std::printf("        \"constrained_size\": %llu,\n", static_cast<unsigned long long>(constrained));
        std::printf("}\n");
    }
}  // namespace

auto main() -> int
{
    std::printf("# Generated by ladder_reference -- do not hand-edit.\n");
    std::printf("# See this file's own header comment for why it exists.\n\n");

    print_rung("RUNG_POOL4", bench::make_pool4_rung());
    print_rung("RUNG_POOL5", bench::make_pool5_rung());
    print_rung("RUNG_POOL6", bench::make_pool6_rung());
    print_rung("RUNG_POOL7", bench::make_pool7_rung());
    print_rung("RUNG_POOL8", bench::make_pool8_rung());
    print_rung("RUNG_REALISTIC_A", bench::make_realistic_rung_a());
    print_rung("RUNG_REALISTIC_B", bench::make_realistic_rung_b());

    std::printf(
        "RUNGS = [RUNG_POOL4, RUNG_POOL5, RUNG_POOL6, RUNG_POOL7, RUNG_POOL8, RUNG_REALISTIC_A, "
        "RUNG_REALISTIC_B]\n");

    return 0;
}
